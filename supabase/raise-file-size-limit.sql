-- ============================================================
--  ⬆️  رفع الحد الأقصى لحجم ملفات الامتحانات (PDF) إلى 50 ميجابايت
-- ============================================================
--
--  لماذا؟ سلة التخزين في Supabase ترفض أي ملف أكبر من الحد المضبوط فيها،
--  ولذلك تظهر رسالة «حجم الملف كبير جداً» حتى لو كان الكود يسمح بالحجم.
--
--  طريقة التنفيذ:
--    1. افتح مشروعك في Supabase.
--    2. من القائمة الجانبية اختر: SQL Editor  →  New query.
--    3. الصق كل ما في هذا الملف ثم اضغط  Run.
--
--  الملف آمن تماماً: يعدّل إعداد السلة فقط، ولا يحذف أي بيانات أو ملفات.
-- ------------------------------------------------------------

update storage.buckets
set file_size_limit = 52428800          -- 50 ميجابايت (50 * 1024 * 1024)
where id = 'exam-files';

-- إن لم تكن السلة موجودة بعد، هذا السطر ينشئها مباشرة:
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('exam-files', 'exam-files', true, 52428800, array['application/pdf'])
on conflict (id) do update
  set public            = true,
      file_size_limit   = 52428800,
      allowed_mime_types = array['application/pdf'];

-- ------------------------------------------------------------
--  للتحقق بعد التنفيذ (يجب أن يظهر 52428800):
-- ------------------------------------------------------------
select id,
       public,
       file_size_limit,
       pg_size_pretty(file_size_limit::bigint) as الحد_المقروء,
       allowed_mime_types
from storage.buckets
where id = 'exam-files';

